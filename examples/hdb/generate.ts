import Database from "better-sqlite3";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse, stringify } from "yaml";
import { mulberry32, shuffle } from "../../src/templates/rng";
import { splitFor } from "../../src/templates/split";
import { templates, type Draft, type Universe } from "../../src/templates/templates";

const SEED = 20260101;
const OUT_FILE = "generated.yaml";
const FLAT_TYPES = ["3 ROOM", "4 ROOM", "5 ROOM", "EXECUTIVE"];

const dbPath = fileURLToPath(new URL("./hdb.db", import.meta.url));
const casesDir = fileURLToPath(new URL("./cases/", import.meta.url));

if (!existsSync(dbPath)) {
  console.error("hdb.db not found. Run: npm run hdb:setup");
  process.exit(1);
}

const db = new Database(dbPath, { readonly: true, fileMustExist: true });

// Universe of values to fill templates with, taken from the data itself.
const towns = db.prepare("SELECT DISTINCT town FROM resale ORDER BY town").pluck().all() as string[];
const dbFlatTypes = new Set(
  db.prepare("SELECT DISTINCT flat_type FROM resale").pluck().all() as string[],
);
// Only complete calendar years (12 distinct months), so partial years are never used.
const years = (
  db
    .prepare(
      "SELECT substr(month, 1, 4) AS y FROM resale GROUP BY y HAVING COUNT(DISTINCT month) = 12 ORDER BY y",
    )
    .pluck()
    .all() as string[]
).map(Number);

const universe: Universe = {
  towns,
  flatTypes: FLAT_TYPES.filter((f) => dbFlatTypes.has(f)),
  years,
};

console.log(`Universe: ${towns.length} towns, flat types [${universe.flatTypes.join(", ")}], years ${years[0]}-${years[years.length - 1]}`);

// Questions already written by hand (every cases file except the generated one).
const existing = new Set<string>();
for (const f of readdirSync(casesDir)) {
  if (f === OUT_FILE || !/\.ya?ml$/.test(f)) continue;
  const raw = parse(readFileSync(join(casesDir, f), "utf8")) as { question?: string }[] | null;
  for (const c of raw ?? []) if (c.question) existing.add(c.question);
}

const num = (sql: string): number => Number(db.prepare(sql).pluck().get());
const passes = (d: Draft): boolean =>
  num(d.supportSql) >= d.minSupport && (!d.tieSql || num(d.tieSql) === 1);

interface OutCase {
  id: string;
  question: string;
  reference_sql: string;
  tags: string[];
  split: "dev" | "test";
}

const rand = mulberry32(SEED);
const out: OutCase[] = [];
const usedIds = new Set<string>();

for (const t of templates) {
  let accepted = 0;
  let rejected = 0;
  for (const d of shuffle(t.drafts(universe), rand)) {
    if (accepted >= t.quota) break;
    if (existing.has(d.question) || usedIds.has(d.id)) continue;
    if (!passes(d)) {
      rejected++;
      continue;
    }
    usedIds.add(d.id);
    out.push({
      id: d.id,
      question: d.question,
      reference_sql: d.sql,
      tags: d.tags,
      split: splitFor(d.id),
    });
    accepted++;
  }
  console.log(`  ${t.name.padEnd(22)} ${accepted}/${t.quota} accepted (${rejected} rejected as too small or tied)`);
  if (accepted < t.quota) console.warn(`  WARNING: ${t.name} could only fill ${accepted} of ${t.quota}`);
}

out.sort((a, b) => a.id.localeCompare(b.id));

const header =
  `# GENERATED by examples/hdb/generate.ts (seed ${SEED}). Do not edit by hand.\n` +
  "# Regenerate with: npm run hdb:generate, then: npm run dev -- compute-expected\n";
writeFileSync(join(casesDir, OUT_FILE), header + stringify(out, { lineWidth: 0 }));

const test = out.filter((c) => c.split === "test").length;
console.log(`\nWrote ${out.length} cases to ${OUT_FILE} (${out.length - test} dev, ${test} test)`);
db.close();